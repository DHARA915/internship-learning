-- Q:9 Create a materialized view: monthly_dashboard - month, total revenue, order count, avg order value, new customers count, top product.

DROP MATERIALIZED VIEW IF  EXISTS MONTHLY_DASHBOARD;

CREATE MATERIALIZED VIEW MONTHLY_DASHBOARD AS 

WITH MONTHS AS (
-- GET ALL MONTHS CONTAINING ORDER AND NEW CUSTOMERS

SELECT DISTINCT DATE_TRUNC('month', ORDER_DATE):: DATE AS MONTH FROM ORDERS
UNION
SELECT DISTINCT DATE_TRUNC('month', CREATED_AT):: DATE FROM USERS
),

MONTHLY_ORDERS AS (
-- MONTHY_ORDER STATISTICS

SELECT  DATE_TRUNC('month',O.ORDER_DATE)::DATE AS MONTH,
        SUM(O.TOTAL_AMOUNT) AS TOTAL_REVENUE,
		COUNT(*) AS ORDER_COUNT,
        AVG(O.TOTAL_AMOUNT) AS AVG_ORDER_VALUE
        FROM ORDERS O
        WHERE O.ORDER_STATUS <> 'CANCELLED'
        GROUP BY DATE_TRUNC('month', O.ORDER_DATE)::DATE		
),

MONTHLY_ORDER_ITEMS  AS (
    SELECT
        DATE_TRUNC('month', O.ORDER_DATE)::DATE AS MONTH,
        COUNT(*) AS TOTAL_ORDER_ITEMS,
        SUM(OI.QUANTITY) AS TOTAL_UNITS_SOLD
    FROM ORDERS O
    INNER JOIN ORDER_ITEMS OI
        ON O.ID = OI.ORDER_ID
    WHERE O.ORDER_STATUS <> 'CANCELLED'
    GROUP BY DATE_TRUNC('month', O.ORDER_DATE)::DATE
),

MONTHLY_CUSTOMERS AS (
SELECT  DATE_TRUNC('month', U.CREATED_AT)::DATE AS MONTH,
COUNT(*) AS NEW_CUSTOMERS_COUNT
FROM USERS U
GROUP BY DATE_TRUNC('month',U.CREATED_AT)::DATE
),

PRODUCT_REVENUE AS (
    SELECT
        DATE_TRUNC('month', O.ORDER_DATE)::DATE AS MONTH,
        P.ID AS PRODUCT_ID,
        P.NAME AS PRODUCT_NAME,
        SUM(OI.LINE_TOTAL) AS PRODUCT_REVENUE
    FROM ORDERS O
    INNER JOIN ORDER_ITEMS OI
        ON O.ID = OI.ORDER_ID
    INNER JOIN PRODUCTS P
        ON P.ID = OI.PRODUCT_ID
    WHERE O.ORDER_STATUS <> 'CANCELLED'
    GROUP BY
        DATE_TRUNC('month', O.ORDER_DATE)::DATE,
        P.ID,
        P.NAME
),

RANKED_PRODUCTS AS (
    SELECT
        MONTH,
        PRODUCT_ID,
        PRODUCT_NAME,
        PRODUCT_REVENUE,

        ROW_NUMBER() OVER (
            PARTITION BY MONTH
            ORDER BY PRODUCT_REVENUE DESC, PRODUCT_ID
        ) AS PRODUCT_RANK

    FROM PRODUCT_REVENUE
)

-- FINAL QUERY
SELECT
    M.MONTH,

    COALESCE(MO.TOTAL_REVENUE, 0)::NUMERIC(14,2)
        AS TOTAL_REVENUE,

    COALESCE(MO.ORDER_COUNT, 0)::BIGINT
        AS ORDER_COUNT,

    COALESCE(MOI.TOTAL_ORDER_ITEMS, 0)::BIGINT
        AS TOTAL_ORDER_ITEMS,

    COALESCE(MOI.TOTAL_UNITS_SOLD, 0)::BIGINT
        AS TOTAL_UNITS_SOLD,

    COALESCE(MO.AVG_ORDER_VALUE, 0)::NUMERIC(14,2)
        AS AVG_ORDER_VALUE,

    COALESCE(MC.NEW_CUSTOMERS_COUNT, 0)::BIGINT
        AS NEW_CUSTOMERS_COUNT,

    RP.PRODUCT_NAME AS TOP_PRODUCT

FROM MONTHS M

LEFT JOIN MONTHLY_ORDERS MO
    ON M.MONTH = MO.MONTH

LEFT JOIN MONTHLY_ORDER_ITEMS MOI
    ON M.MONTH = MOI.MONTH

LEFT JOIN MONTHLY_CUSTOMERS MC
    ON M.MONTH = MC.MONTH

LEFT JOIN RANKED_PRODUCTS RP
    ON M.MONTH = RP.MONTH
    AND RP.PRODUCT_RANK = 1

ORDER BY M.MONTH;

EXPLAIN ANALYZE
SELECT * FROM MONTHLY_DASHBOARD ORDER BY MONTH;

-- Q:10 Write a full analytics report using CTEs: customer segments 
-- (by total spend), revenue trends (month over month % change using LAG),
-- product performance (revenue rank using DENSE_RANK)

-- 1 => CUSTOMER SEGMENTATION

EXPLAIN (ANALYZE,BUFFERS)
WITH CUSTOMER_SPENDING AS (
-- CALCULATE TOTAL SEPNDING PER CUSTOMER 
SELECT 
   U.ID AS CUSTOMER_ID,
   U.NAME AS CUSTOMER_NAME,
   COUNT(O.ID) AS ORDER_COUNT,
   COALESCE(SUM(O.TOTAL_AMOUNT),0) AS TOTAL_SPENT
   FROM USERS U 
   LEFT JOIN ORDERS O
        ON U.ID = O.USER_ID
		AND O.ORDER_STATUS<>'CANCELLED'

   GROUP BY U.ID , U.NAME
),

CUSTOMER_SEGMENTS AS (
 SELECT CUSTOMER_ID , CUSTOMER_NAME , ORDER_COUNT, TOTAL_SPENT,

 NTILE(3) OVER (
 ORDER BY TOTAL_SPENT DESC , CUSTOMER_ID 
 ) AS SEGMENT_NUMBER
 
  FROM CUSTOMER_SPENDING
)

-- DISPLAY CUSTOMER_SEGMENTS

SELECT 
CUSTOMER_ID, 
CUSTOMER_NAME,
ORDER_COUNT,
TOTAL_SPENT,

 CASE
   WHEN SEGMENT_NUMBER = 1 THEN 'HIGH VALUE'
   WHEN SEGMENT_NUMBER = 2 THEN 'MIDIUM VALUE'
   ELSE 'LOW VALUE'
 END AS CUSTOMER_SEGMENTS
FROM CUSTOMER_SEGMENTS ORDER BY TOTAL_SPENT DESC;

-- 2 => REVENUE TRENDS - MONTH-OVER-MONTH PERCENTAGE CHANGE

-- CALCULATE TOTAL_REVENUE FOR EACH MONTH
WITH MONTHLY_REVENUE AS (

 SELECT DATE_TRUNC('month',ORDER_DATE)::DATE AS MONTH,
 SUM(TOTAL_AMOUNT) AS TOTAL_REVENUE
  FROM ORDERS
   WHERE ORDER_STATUS<>'CANCELLED'

    GROUP BY DATE_TRUNC('month', ORDER_DATE)::DATE
),

-- GET PREVIOUS MONTH'S REVENUE
 REVENUE_COMPARISON  AS (
  SELECT MONTH, TOTAL_REVENUE , 
  LAG(TOTAL_REVENUE) OVER(
     ORDER BY MONTH
  ) AS PREVIOUS_MONTH_REVENUE

FROM MONTHLY_REVENUE
 )  

-- CALCULATE MONTH OVER MONTH PERCENTAGE CHANGE

SELECT MONTH,TOTAL_REVENUE , PREVIOUS_MONTH_REVENUE,
       CASE 
	      WHEN PREVIOUS_MONTH_REVENUE IS NULL
		    OR PREVIOUS_MONTH_REVENUE = 0
		  THEN NULL
		  
	   ELSE ROUND (
            (
              (TOTAL_REVENUE - PREVIOUS_MONTH_REVENUE)
			  / PREVIOUS_MONTH_REVENUE
			)*100,
			2
	      ) 
	   END AS MOM_CHANGE_PERCENTAGE
  FROM REVENUE_COMPARISON
ORDER BY MONTH;

--  3 => PRODUCT PERFORMANCE - REVENUE RANKING USING DENSE_RANK()

EXPLAIN (ANALYZE, BUFFERS)
WITH PRODUCT_REVENUE AS (
SELECT
 P.ID AS PRODUCT_ID,
 P.NAME AS PRODUCT_NAME,
 P.CATEGORY,
 COALESCE(SUM(OI.LINE_TOTAL),0) AS TOTAL_REVENUE,
 COALESCE(SUM(OI.QUANTITY),0) AS TOTAL_UNIT_SOLD

  FROM PRODUCTS P

    LEFT JOIN ORDER_ITEMS OI
        ON P.ID = OI.PRODUCT_ID

    LEFT JOIN ORDERS O
        ON O.ID = OI.ORDER_ID
        AND O.ORDER_STATUS <> 'CANCELLED'

    GROUP BY
        P.ID,
        P.NAME,
        P.CATEGORY
),


PRODUCT_RANKING AS (
-- RANK PRODUCTS BASED ON REVENUE WITIN EACH CATEGORY
SELECT PRODUCT_ID,
PRODUCT_NAME,
CATEGORY,
TOTAL_REVENUE,
TOTAL_UNIT_SOLD,

DENSE_RANK() OVER(
   PARTITION BY CATEGORY
   ORDER BY TOTAL_REVENUE DESC
) AS REVENUE_RANK
 FROM PRODUCT_REVENUE
)

-- DISPLAY PRODUCTS PERFORMANCE
SELECT * FROM PRODUCT_RANKING ORDER BY CATEGORY , REVENUE_RANK;


