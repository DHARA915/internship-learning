-- PROJECT MANAGEMENT TABLES

-- SHOW ALL TABLES
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
AND table_type = 'BASE TABLE'
ORDER BY table_name;

-- CREATE PRIORITY ENUM
CREATE TYPE task_priority AS ENUM (
'critical',
'high',
'medium',
'low'
)

-- WORKSPACES 
CREATE TABLE WORKSPACES (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(150) NOT NULL UNIQUE,
    DESCRIPTION TEXT,
    CREATED_AT TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- USERS
CREATE TABLE USERS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL UNIQUE,
    CREATED_AT TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- PROJECTS
CREATE TABLE PROJECTS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    WORKSPACE_ID BIGINT NOT NULL,
    NAME VARCHAR(150) NOT NULL,
    DESCRIPTION TEXT,
    CREATED_AT TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PROJECT_WORKSPACE
        FOREIGN KEY (WORKSPACE_ID)
        REFERENCES WORKSPACES(ID)
        ON DELETE CASCADE,

    CONSTRAINT UQ_PROJECT_WORKSPACE_NAME
        UNIQUE (WORKSPACE_ID, NAME)
);

-- BOARDS
CREATE TABLE BOARDS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PROJECT_ID BIGINT NOT NULL UNIQUE,
    NAME VARCHAR(150) NOT NULL,

    CONSTRAINT FK_BOARD_PROJECT
        FOREIGN KEY (PROJECT_ID)
        REFERENCES PROJECTS(ID)
        ON DELETE CASCADE
);

-- BOARD_COLUMNS
CREATE TABLE BOARD_COLUMNS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    BOARD_ID BIGINT NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    POSITION INTEGER NOT NULL,

    CONSTRAINT FK_COLUMN_BOARD
        FOREIGN KEY (BOARD_ID)
        REFERENCES BOARDS(ID)
        ON DELETE CASCADE,

    CONSTRAINT CHK_COLUMN_POSITION
        CHECK (POSITION > 0),

    CONSTRAINT UQ_BOARD_COLUMN_NAME
        UNIQUE (BOARD_ID, NAME),

    CONSTRAINT UQ_BOARD_COLUMN_POSITION
        UNIQUE (BOARD_ID, POSITION)
);

-- TASKS
CREATE TABLE TASKS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    BOARD_COLUMN_ID BIGINT NOT NULL,

    TITLE VARCHAR(200) NOT NULL,
    DESCRIPTION TEXT,

    PRIORITY TASK_PRIORITY NOT NULL DEFAULT 'medium',

    ASSIGNEE_ID BIGINT,
    REPORTER_ID BIGINT,

    ESTIMATED_HOURS NUMERIC(8,2) DEFAULT 0,
    ACTUAL_HOURS NUMERIC(8,2) DEFAULT 0,

    DUE_DATE DATE,

    CUSTOM_FIELDS JSONB DEFAULT '{}'::JSONB,

    CREATED_AT TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_TASK_COLUMN
        FOREIGN KEY (BOARD_COLUMN_ID)
        REFERENCES BOARD_COLUMNS(ID)
        ON DELETE RESTRICT,

    CONSTRAINT FK_TASK_ASSIGNEE
        FOREIGN KEY (ASSIGNEE_ID)
        REFERENCES USERS(ID)
        ON DELETE SET NULL,

    CONSTRAINT FK_TASK_REPORTER
        FOREIGN KEY (REPORTER_ID)
        REFERENCES USERS(ID)
        ON DELETE SET NULL,

    CONSTRAINT CHK_ESTIMATED_HOURS
        CHECK (ESTIMATED_HOURS >= 0),

    CONSTRAINT CHK_ACTUAL_HOURS
        CHECK (ACTUAL_HOURS >= 0),

    CONSTRAINT CHK_CUSTOM_FIELDS
        CHECK (JSONB_TYPEOF(CUSTOM_FIELDS) = 'object')
);

-- TASK_COMMENTS
CREATE TABLE TASK_COMMENTS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TASK_ID BIGINT NOT NULL,
    USER_ID BIGINT,
    COMMENT TEXT NOT NULL,
    CREATED_AT TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_COMMENT_TASK
        FOREIGN KEY (TASK_ID)
        REFERENCES TASKS(ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_COMMENT_USER
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(ID)
        ON DELETE SET NULL
);

-- LABELS
CREATE TABLE LABELS (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL UNIQUE
);

-- TASK_LABELS
CREATE TABLE TASK_LABELS (
    TASK_ID BIGINT NOT NULL,
    LABEL_ID BIGINT NOT NULL,

    PRIMARY KEY (TASK_ID, LABEL_ID),

    CONSTRAINT FK_TASK_LABEL_TASK
        FOREIGN KEY (TASK_ID)
        REFERENCES TASKS(ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_TASK_LABEL_LABEL
        FOREIGN KEY (LABEL_ID)
        REFERENCES LABELS(ID)
        ON DELETE CASCADE
);

-- TASK HISTORY
CREATE TABLE TASK_HISTORY (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TASK_ID BIGINT NOT NULL,
    OLD_STATUS VARCHAR(100) NOT NULL,
    NEW_STATUS VARCHAR(100) NOT NULL,
    CHANGED_BY BIGINT,
    CHANGED_AT TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_HISTORY_TASK
        FOREIGN KEY (TASK_ID)
        REFERENCES TASKS(ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_HISTORY_USER
        FOREIGN KEY (CHANGED_BY)
        REFERENCES USERS(ID)
        ON DELETE SET NULL,

    CONSTRAINT CHK_STATUS_CHANGE
        CHECK (OLD_STATUS <> NEW_STATUS)
);

