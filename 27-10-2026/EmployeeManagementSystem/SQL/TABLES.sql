-- Create database
CREATE DATABASE EmplyeeManagement;


-- Department
CREATE TABLE DEPT (
    ID              INTEGER PRIMARY KEY,
    NAME            VARCHAR(200) NOT NULL,
    BUDGET          INTEGER NOT NULL CHECK (BUDGET > 0),
    CREATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE DEPT ADD CONSTRAINT unique_dept_name  UNIQUE(NAME);

-- Employees
CREATE TABLE EMP (
    ID              INTEGER PRIMARY KEY,
    NAME            VARCHAR(100) NOT NULL,
    EMAIL           VARCHAR(255) UNIQUE,
    AGE             INTEGER CHECK (AGE >= 18),
    SALARY          INTEGER CHECK (SALARY > 0),
    DEPARTMENT_ID   INTEGER,
    MANAGER_ID      INTEGER,
    IS_ACTIVE       BOOLEAN NOT NULL DEFAULT TRUE,
    JOINING_DATE    DATE NOT NULL DEFAULT CURRENT_DATE,
    DESIGNATION     VARCHAR(100),
    CREATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_emp_dept
        FOREIGN KEY (DEPARTMENT_ID)
        REFERENCES DEPT(ID)
        ON DELETE SET NULL,

    CONSTRAINT fk_emp_manager
        FOREIGN KEY (MANAGER_ID)
        REFERENCES EMP(ID)
        ON DELETE SET NULL
);


-- Attendance
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID   INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMP_ID          INTEGER NOT NULL,
    WORK_DATE       DATE NOT NULL,
    CHECK_IN        TIME,
    CHECK_OUT       TIME,
    STATUS          VARCHAR(10) NOT NULL DEFAULT 'PRESENT',
    REMARKS         VARCHAR(200),
    CREATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_att_status
        CHECK (
            STATUS IN (
                'PRESENT',
                'ABSENT',
                'HALF_DAY',
                'ON_LEAVE',
                'HOLIDAY')
				),
    CONSTRAINT chk_att_time
        CHECK (
            CHECK_OUT IS NULL
            OR CHECK_IN IS NULL
            OR CHECK_OUT > CHECK_IN
        ),

    CONSTRAINT uq_att_emp_date
        UNIQUE (EMP_ID, WORK_DATE),

    CONSTRAINT fk_att_emp
        FOREIGN KEY (EMP_ID)
        REFERENCES EMP(ID)
        ON DELETE CASCADE
);


-- Leave types
CREATE TABLE LEAVE_TYPES (
    LEAVE_TYPE_ID   INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TYPE_NAME       VARCHAR(50) NOT NULL UNIQUE,
    MAX_DAYS_YEAR   INTEGER NOT NULL CHECK (MAX_DAYS_YEAR >= 0),
    IS_PAID         BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- Leave balances
CREATE TABLE LEAVE_BALANCES (
    BALANCE_ID      INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMP_ID          INTEGER NOT NULL,
    LEAVE_TYPE_ID   INTEGER NOT NULL,
    YEAR            INTEGER NOT NULL CHECK (YEAR >= 2000),
    ALLOCATED_DAYS  INTEGER NOT NULL CHECK (ALLOCATED_DAYS >= 0),
    USED_DAYS       INTEGER NOT NULL DEFAULT 0 CHECK (USED_DAYS >= 0),
    CREATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_used_le_allocated
        CHECK (USED_DAYS <= ALLOCATED_DAYS),

    CONSTRAINT uq_balance
        UNIQUE (EMP_ID, LEAVE_TYPE_ID, YEAR),

    CONSTRAINT fk_bal_emp
        FOREIGN KEY (EMP_ID)
        REFERENCES EMP(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_bal_type
        FOREIGN KEY (LEAVE_TYPE_ID)
        REFERENCES LEAVE_TYPES(LEAVE_TYPE_ID)
        ON DELETE RESTRICT
);


-- Leave requests
CREATE TABLE LEAVE_REQUESTS (
    LEAVE_ID       INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMP_ID         INTEGER NOT NULL,
    LEAVE_TYPE_ID  INTEGER NOT NULL,
    START_DATE     DATE NOT NULL,
    END_DATE       DATE NOT NULL,
    REASON         VARCHAR(500),
    STATUS         VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    APPLIED_ON     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    APPROVED_BY    INTEGER,
    DECISION_ON    TIMESTAMPTZ,
    CREATED_AT     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_leave_dates
        CHECK (END_DATE >= START_DATE),

    CONSTRAINT chk_leave_status
        CHECK (
            STATUS IN (
                'PENDING',
                'APPROVED',
                'REJECTED',
                'CANCELLED'
            )
        ),

    CONSTRAINT fk_leave_emp
        FOREIGN KEY (EMP_ID)
        REFERENCES EMP(ID)
        ON DELETE CASCADE,

    CONSTRAINT fk_leave_type
        FOREIGN KEY (LEAVE_TYPE_ID)
        REFERENCES LEAVE_TYPES(LEAVE_TYPE_ID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_leave_approver
        FOREIGN KEY (APPROVED_BY)
        REFERENCES EMP(ID)
        ON DELETE SET NULL
);


-- Salary records
CREATE TABLE SALARY_RECORDS (
    SALARY_ID       INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMP_ID          INTEGER NOT NULL,
    PAY_MONTH       INTEGER NOT NULL CHECK (PAY_MONTH BETWEEN 1 AND 12),
    PAY_YEAR        INTEGER NOT NULL CHECK (PAY_YEAR >= 2000),
    BASIC_SALARY    INTEGER NOT NULL CHECK (BASIC_SALARY >= 0),
    ALLOWANCES      INTEGER NOT NULL DEFAULT 0 CHECK (ALLOWANCES >= 0),
    BONUS           INTEGER NOT NULL DEFAULT 0 CHECK (BONUS >= 0),
    DEDUCTIONS      INTEGER NOT NULL DEFAULT 0 CHECK (DEDUCTIONS >= 0),
    PAYMENT_DATE    DATE,
    PAYMENT_STATUS  VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    CREATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_pay_status
        CHECK (
            PAYMENT_STATUS IN (
                'PENDING',
                'PAID',
                'FAILED'
            )
        ),

    CONSTRAINT uq_salary_month
        UNIQUE (EMP_ID, PAY_MONTH, PAY_YEAR),

    CONSTRAINT fk_sal_emp
        FOREIGN KEY (EMP_ID)
        REFERENCES EMP(ID)
        ON DELETE CASCADE
);