-- Q:8 Create a trigger: AFTER INSERT on order_items, auto-update product stock quantity (decrement)

-- CREATE TRIGGER FUNCTION
CREATE OR REPLACE  FUNCTION UPDATE_PRODUCT_STOCK()
RETURNS TRIGGER
LANGUAGE PLPGSQL
AS $$
BEGIN

-- UPDATE PRODUCT STOCK
UPDATE PRODUCTS SET
STOCK_QUANTITY = STOCK_QUANTITY - NEW.QUANTITY
WHERE  ID = NEW.PRODUCT_ID
 AND STOCK_QUANTITY>= NEW.QUANTITY;

IF NOT FOUND THEN 
   RAISE EXCEPTION 'Insufficient stock for product ID %',
      NEW.PRODUCT_ID;
END IF;

-- UPDATE TOTAL_AMOUNT IN ORDERS TABLE
UPDATE ORDERS
SET TOTAL_AMOUNT = TOTAL_AMOUNT + NEW.LINE_TOTAL
WHERE ID = NEW.ORDER_ID;

RETURN NEW;

END;
$$;

