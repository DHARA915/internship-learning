-- For creating database;
CREATE DATABASE database_name;

-- CREATING TABLES................................................................


-- AUTHORS
CREATE TABLE AUTHORS (
ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
NAME VARCHAR(100) NOT NULL,
BIO TEXT,
COUNTRY VARCHAR(100)
);

-- CATEGORIES

CREATE TABLE CATEGORIES (
ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
NAME VARCHAR(100) UNIQUE NOT NULL
);

-- CUSTOMERS

CREATE TABLE CUSTOMERS(
ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
NAME VARCHAR(255) NOT NULL,
EMAIL VARCHAR(255) NOT NULL UNIQUE,
PHONE VARCHAR(20),
ADDRESS TEXT,
CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW()
);

-- BOOKS 
CREATE TABLE BOOKS(
ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
TITLE VARCHAR(200) NOT NULL,
ISBN VARCHAR(20) NOT NULL UNIQUE,
PRICE NUMERIFC(10,2) NOT NULL CHECK(PRICE>=0),
STOCK_QUANTITY INTEGER NOT NULL DEFAULT 0 CHECK(STOCK_QUANTITY>=0),

AUTHOR_ID INTEGER 
          REFERENCES AUTHORS(ID)
		  ON DELETE SET NULL,

CATEGORY_ID INTEGER NOT NULL 
          REFERENCES CATEGORIES(ID)
		  ON DELETE RESTRICT
);

-- ORDER 

CREATE TABLE ORDERS (
ID INTEGER GENERATED ALWAYS AS IDENTITY  PRIMARY KEY,

CUSTOMER_ID INTEGER NOT NULL
           REFERENCES CUSTOMERS(ID)
		   ON DELETE RESTRICT,
ORDER_DATE TIMESTAMP NOT NULL DEFAULT NOW(),

STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING'
  CHECK(
    STATUS IN(
              'PENDING',
			  'CONFIRMED',
			  'SHIPPED',
			  'DELIVERED',
			  'CANCELLED'
	)
  ),
 
TOTAL_AMOUNT NUMERIC(12,2) NOT NULL DEFAULT 0
      CHECK(TOTAL_AMOUNT>=0)
);

-- ORDER ITEMS.

CREATE TABLE ORDER_ITEMS (

ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

ORDER_ID INTEGER NOT NULL
      REFERENCES ORDERS(ID)
	  ON DELETE CASCADE ,

BOOK_ID INTEGER NOT NULL
        REFERENCES BOOKS(ID)
		ON DELETE RESTRICT,

QUANTITY INTEGER NOT NULL CHECK(QUANTITY>0),
UNITPRICE NUMERIC(10,2) NOT NULL CHECK (UNITPRICE>=0),

LINE_TOTAL NUMERIC(12,2)
         GENERATED ALWAYS AS (QUANTITY*UNITPRICE) STORED,

CONSTRAINT uq_order_book UNIQUE (ORDER_ID, BOOK_ID)
);

-- JUNCTION TABLE - BOOK_AUTHORS 

CREATE TABLE BOOK_AUTHORS (
 BOOK_ID INTEGER NOT NULL
         REFERENCES BOOKS(ID)
		 ON DELETE CASCADE,
AUTHOR_ID INTEGER NOT NULL
         REFERENCES AUTHORS(ID)
		 ON DELETE CASCADE,

PRIMARY KEY(BOOK_ID, AUTHOR_ID)
);


