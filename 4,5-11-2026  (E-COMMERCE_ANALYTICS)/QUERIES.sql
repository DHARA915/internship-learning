-- Q:1 CTE + Window: Rank products by revenue within each category, show top 3 per category.
WITH PRODUCT_REVENUE AS (

    SELECT
        P.ID AS PRODUCT_ID,
        P.NAME AS PRODUCT_NAME,
        P.CATEGORY,

        SUM(OI.LINE_TOTAL) AS TOTAL_REVENUE

    FROM PRODUCTS P

    INNER JOIN ORDER_ITEMS OI
        ON P.ID = OI.PRODUCT_ID

    INNER JOIN ORDERS O
        ON OI.ORDER_ID = O.ID

    WHERE O.ORDER_STATUS <> 'CANCELLED'

    GROUP BY
        P.ID,
        P.NAME,
        P.CATEGORY

),

PRODUCT_RANKING AS (

    SELECT
        PRODUCT_ID,
        PRODUCT_NAME,
        CATEGORY,
        TOTAL_REVENUE,

        DENSE_RANK() OVER (
            PARTITION BY CATEGORY
            ORDER BY TOTAL_REVENUE DESC
        ) AS REVENUE_RANK

    FROM PRODUCT_REVENUE

)

SELECT *
FROM PRODUCT_RANKING
WHERE REVENUE_RANK <= 3
ORDER BY CATEGORY, REVENUE_RANK;

-- Q:2 Window: For each order, show running total of customer's spending using SUM OVER (PARTITION BY customer ORDER BY order_date)
SELECT U.ID AS USER_ID , U.NAME AS CUSTOMER_NAME, O.ID AS ORDER_ID , O.ORDER_DATE ,O.ORDER_STATUS, O.TOTAL_AMOUNT,
SUM(O.TOTAL_AMOUNT) OVER (
PARTITION BY O.USER_ID
ORDER BY O.ORDER_DATE , O.ID
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
) AS RUNNING_TOTAL

FROM USERS U 
INNER JOIN ORDERS O 
      ON U.ID  = O.USER_ID
WHERE O.ORDER_STATUS <> 'CANCELLED'

ORDER BY 
      O.USER_ID,
	  O.ORDER_DATE,
	  O.ID;

-- Q:3 LAG/LEAD: For each customer, show days between consecutive orders.

SELECT U.ID AS CUSTOMER_ID , U.NAME AS CUSTOMER_NAME,O.ID AS ORDER_ID ,
O.ORDER_DATE ,

LAG(O.ORDER_DATE) OVER(
PARTITION BY O.USER_ID
ORDER BY O.ORDER_DATE , O.ID
) AS PREVIOUS_ORDER_DATE,

LEAD(O.ORDER_DATE) OVER(
PARTITION BY O.USER_ID
ORDER BY O.ORDER_DATE, O.ID
) AS NEXT_ORDER_DATE,

O.ORDER_DATE:: DATE -
LAG(O.ORDER_DATE::DATE) OVER (
PARTITION BY O.USER_ID
ORDER BY O.ORDER_DATE , O.ID
) AS DAYS_SINCE_PREVIOUS_ORDER,

LEAD(O.ORDER_DATE::DATE) OVER (
PARTITION BY O.USER_ID
ORDER  BY O.ORDER_DATE , O.ID
) -  O.ORDER_DATE::DATE AS DAYS_UNTILL_NEXT_ORDER

FROM USERS U
INNER JOIN ORDERS O
      ON U.ID = O.USER_ID
ORDER BY
      O.USER_ID,
	  O.ORDER_DATE,
	  O.ID;

-- Q:4 Recursive CTE: Products have a 'related_product_id' - write recursive query to find chain of related products.

WITH RECURSIVE PRODUCT_CHAIN AS (
-- ANCHOR QUERY
SELECT P.ID , P.NAME AS PRODUCT_NAME , P.RELATED_PRODUCT_ID , 1 AS LEVEL , P.ID AS ROOT_PRODUCT_ID
FROM PRODUCTS P
WHERE NOT EXISTS(
SELECT 1 FROM PRODUCTS CHILD
WHERE CHILD.RELATED_PRODUCT_ID = P.ID
)

UNION ALL

-- RECURSIVE QUERY 

SELECT P.ID , P.NAME , P.RELATED_PRODUCT_ID , PC.LEVEL + 1 , PC.ROOT_PRODUCT_ID
FROM PRODUCTS P 
INNER JOIN PRODUCT_CHAIN PC
      ON P.ID = PC.RELATED_PRODUCT_ID	 
)
-- FINAL QUERY
SELECT * FROM PRODUCT_CHAIN ORDER BY ROOT_PRODUCT_ID , LEVEL;

