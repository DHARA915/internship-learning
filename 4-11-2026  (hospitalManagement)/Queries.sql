-- QUERIES.

-- SELECT ALL DATA FROM TABLES.

SELECT * FROM DOCTORS;
SELECT * FROM PATIENTS;
SELECT * FROM APPOINTMENTS;
SELECT * FROM PRESCRIPTIONS;

-- Q:1 Find doctors with the most appointments this month.
SELECT D.ID AS DOCTOR_ID , D.NAME AS DOCTOR_NAME  , 
TO_CHAR(A.APPOINTMENT_DATE, 'Month') AS MONTH, 
COUNT(A.DOCTOR_ID) AS TOTAL_APPOINTMENTS 
FROM DOCTORS D 
INNER JOIN APPOINTMENTS A
      ON D.ID = A.DOCTOR_ID
WHERE
A.APPOINTMENT_DATE >= DATE_TRUNC('MONTH', CURRENT_DATE)
AND
A.APPOINTMENT_DATE < DATE_TRUNC('MONTH', CURRENT_DATE) + INTERVAL '1 MONTH'
GROUP BY D.ID,D.NAME,TO_CHAR(A.APPOINTMENT_DATE, 'Month')
ORDER BY TOTAL_APPOINTMENTS DESC;

-- Q:2 List patients who visited more than 2 different doctors.
SELECT 
   P.ID AS PATIENT_ID ,
   P.NAME AS PATIENT_NAME,
   COUNT(DISTINCT A.DOCTOR_ID) AS TOTAL_DOCTORS
FROM PATIENTS P 
INNER JOIN APPOINTMENTS A
      ON P.ID = A.PATIENT_ID
GROUP BY P.ID , P.NAME
HAVING COUNT(DISTINCT A.DOCTOR_ID) > 2 ;

-- Q:3 Show each doctor's schedule for today (all appointments ordered by time).

SELECT D.ID AS DOCTOR_ID, D.NAME AS DOCTOR_NAME , P.ID AS PATIENT_ID ,
P.NAME AS PATIENT_NAME, A.APPOINTMENT_DATE, A.STATUS, A.NOTES

FROM DOCTORS D
INNER JOIN APPOINTMENTS A
      ON D.ID = A.DOCTOR_ID
INNER JOIN PATIENTS P 
      ON A.PATIENT_ID = P.ID
WHERE A.APPOINTMENT_DATE::DATE = CURRENT_DATE

ORDER BY 
      D.NAME, A.APPOINTMENT_DATE;

-- Q:4 Find the busiest day of the week for appointments (GROUP BY EXTRACT(dow)).

SELECT 
  EXTRACT(DOW FROM APPOINTMENT_DATE) AS DAY_NUMBER,
  TO_CHAR(APPOINTMENT_DATE,'FMDay') AS DAY_NAME,
  COUNT(*) AS TOTAL_APPOITMENTS
FROM APPOINTMENTS 
GROUP BY 
  EXTRACT(DOW FROM APPOINTMENT_DATE),
  TO_CHAR(APPOINTMENT_DATE,'FMDay')
ORDER BY TOTAL_APPOITMENTS DESC LIMIT 1;

-- Q:5 Calculate average appointments per doctor per month.

SELECT D.ID AS DOCTOR_ID0, D.NAME AS DOCTOR_NAME ,
COUNT(A.ID) AS TOTAL_APPOINTMENTS,
ROUND(
COUNT(A.ID)::NUMERIC/
COUNT(DISTINCT DATE_TRUNC('MONTH',A.APPOINTMENT_DATE)),
2
) AS AVG_APPOINTMENT_PER_MONTH
FROM DOCTORS D 
 LEFT JOIN APPOINTMENTS A
   ON D.ID = A.DOCTOR_ID
GROUP BY D.ID , D.NAME
ORDER BY D.ID;

-- Q:6 Find patients who have cancelled more than 1 appointment.

SELECT P.ID AS PATIENT_ID,P.NAME AS PATIENT_NAME,COUNT(A.ID) AS TOTAL_CANCEL_APPOINTMENTS
FROM PATIENTS P 
INNER JOIN APPOINTMENTS A
         ON P.ID = A.PATIENT_ID
WHERE A.STATUS = 'CANCELLED'
GROUP BY P.ID , P.NAME 
HAVING COUNT(A.ID)>1;

-- Q:7 List doctors who have no appointments in the last 7 days.

SELECT
    D.ID AS DOCTOR_ID,
    D.NAME AS DOCTOR_NAME,
    D.SPECIALIZATION
FROM DOCTORS D

LEFT JOIN APPOINTMENTS A
    ON D.ID = A.DOCTOR_ID
    AND A.APPOINTMENT_DATE >= CURRENT_DATE - INTERVAL '7 DAYS'
    AND A.APPOINTMENT_DATE < CURRENT_DATE + INTERVAL '1 DAY'

WHERE A.ID IS NULL;

-- Q:8 Show prescription history for a specific patient: date, doctor name, medicines with dosage.

SELECT P.ID AS PATIENT_ID , P.NAME AS PATIENT_NAME , D.NAME AS DOCTOR_NAME,
A.APPOINTMENT_DATE, PR.MEDICINE_NAME,PR.DOSAGE,PR.DURATION_DAYS

FROM PATIENTS P
INNER JOIN APPOINTMENTS A
      ON P.ID = A.PATIENT_ID
INNER JOIN DOCTORS D
      ON A.DOCTOR_ID = D.ID
INNER JOIN PRESCRIPTIONS PR
       ON A.ID = PR.APPOINTMENT_ID
WHERE P.ID=1
ORDER BY APPOINTMENT_DATE;

-- Q:9 Create a VIEW: doctor_dashboard - name, specialization, total patients, appointments today, completed vs cancelled ratio
CREATE VIEW doctor_dashboar AS(
SELECT D.ID AS DOCTOR_ID, D.NAME AS DOCTOR_NAME , D.SPECIALIZATION,
COUNT(DISTINCT A.PATIENT_ID) AS TOTAL_PATIENTS,
COUNT(A.ID) FILTER (
        WHERE A.APPOINTMENT_DATE::DATE = CURRENT_DATE
    ) AS APPOINTMENTS_TODAY,
COUNT(A.ID) FILTER (
    WHERE A.STATUS = 'COMPLETED'
) AS COMPLETED_APPOINTMENTS,
COUNT(A.ID) FILTER  (
    WHERE A.STATUS = 'CANCELLED'
) AS CANCELLED_APPOINTMENTS,

ROUND(
   COUNT(A.ID) FILTER (WHERE A.STATUS ='COMPLETED') :: NUMERIC
   /
   NULLIF (
     COUNT(A.ID) FILTER (
       WHERE A.STATUS IN('COMPLETED', 'CANCELLED')
	 ),0
   )*100,
  2
) AS  COMPLETED_PERCENTAGE

FROM DOCTORS D
 LEFT JOIN APPOINTMENTS A 
      ON D.ID = A.DOCTOR_ID
GROUP BY D.ID , D.NAME , D.SPECIALIZATION

);

